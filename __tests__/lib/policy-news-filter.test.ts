/**
 * 정책뉴스 걸러내기 회귀 테스트.
 *
 * 여기 적힌 제목들은 **실제로 정책브리핑 API에서 받아온 것**이다. 지어낸 예가 아니다.
 * 낱말 하나로 판정하던 시절 아래 네 건이 첫 화면에 올라왔고, 그때의 판정 실수를
 * 그대로 고정해 둔다. 키워드 목록을 넓히다 보면 같은 실수가 다시 난다.
 */
import { describe, expect, it } from 'vitest'
import { isRentalPolicy } from '@/lib/policy-news'

describe('임대차 기사 판정', () => {
  describe('들어와야 하는 것', () => {
    const keep: Array<[string, string]> = [
      [
        '월세 부담 낮추고 임대 수익은 보장…‘전월세 안심신탁’ 출시',
        '임차인은 전세계약으로 임대료 절감, 전세사기 위험 차단',
      ],
      [
        '내년 공적주택 21.8만 호 공급 …청년월세 지원 대폭 확대',
        '국토부 역대 최대 6조 2000억 원 예산',
      ],
      // 제목에 강한 낱말이 없지만 '주거안정'이 제목에 있다 — 약한 낱말의 통과 조건.
      ["2030년까지 공적주택 119만 호 공급…'주거안정플랜' 마련", '보편형 공공임대 19만 호 공급'],
      ['[해명] 주거복지 정책 및 보편형 임대주택의 세부내용은 확정된 바 없습니다.', ''],
    ]

    it.each(keep)('통과: %s', (title, subtitle) => {
      expect(isRentalPolicy(title, subtitle)).toBe(true)
    })
  })

  describe('걸러야 하는 것', () => {
    /**
     * 넷 다 제목에는 임대차가 없고 부제에 '공공임대'나 '월세'가 한 번 스쳤을 뿐이다.
     * 기사의 주제는 제목에 적힌다.
     */
    const drop: Array<[string, string]> = [
      [
        '"잠재력에 투자"…25조 늘어난 내년 청년 예산, 사용처 들여다보니',
        '내년 공공임대 10만 6000호 공급…72만 명에 일경험·직업훈련 지원',
      ],
      [
        '구 부총리 "경제 회복세 뚜렷…1인당 GNI 4만 달러 가능성 확대"',
        '경제관계장관회의 주재…공실 지식산업센터, 청년·신혼부부 공공임대 전환',
      ],
      [
        '내년 청년정책에 43조 투입…취업부터 주거·혼인·출산 집중 지원',
        '공공임대·장학금·미래적금 확대',
      ],
      // 재난 복구다. 이재민 월세 지원은 계약을 앞둔 사람이 찾는 정보가 아니다.
      [
        '8월 호우 피해 이재민에 추석 전 주거 안정 지원',
        '장기 대피 107세대에 월세·친인척집 거주 체재비 지원',
      ],
    ]

    it.each(drop)('제외: %s', (title, subtitle) => {
      expect(isRentalPolicy(title, subtitle)).toBe(false)
    })
  })

  describe('같은 낱말, 다른 세계', () => {
    it('농지 임대차는 집 이야기가 아니다', () => {
      expect(
        isRentalPolicy(
          '[사실은 이렇습니다] 고령농 농지·상속 농지의 임대차는 처분 대상이 아닙니다',
          ''
        )
      ).toBe(false)
    })

    it('상가건물 임대차도 제외한다', () => {
      expect(isRentalPolicy('상가건물 임대차보호법 개정안 의결', '')).toBe(false)
    })
  })

  it('아무 낱말도 없으면 통과하지 않는다', () => {
    expect(isRentalPolicy('철강산업 고도화 방안 4분기 발표', '무역기반 금융범죄 점검')).toBe(false)
  })

  it('부제가 비어도 제목만으로 판정한다', () => {
    expect(isRentalPolicy('전세사기 피해자 지원 확대', '')).toBe(true)
  })
})
